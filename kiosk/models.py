class ExtractionLog(models.Model):
    """
    Audit log for AI extraction attempts, schema validations, and retries.
    """
    session = models.ForeignKey(PatientSession, on_delete=models.CASCADE, related_name='extraction_logs', null=True, blank=True)
    raw_transcript = models.TextField()
    raw_llm_response = models.TextField()
    parsed_output = models.JSONField(default=dict, blank=True)
    is_valid = models.BooleanField(default=True)
    validation_error = models.TextField(blank=True, default='')
    retry_count = models.IntegerField(default=0)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"ExtractionLog #{self.id} (valid={self.is_valid})"


