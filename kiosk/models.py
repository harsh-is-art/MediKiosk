class MedicalDocument(models.Model):
    """
    Prescriptions, handwritten slips, and lab reports with confidence metrics.
    """
    STATUS_CHOICES = [
        ('uploaded', 'Uploaded'),
        ('processing', 'Processing'),
        ('processed', 'Processed'),
        ('needs_review', 'Needs Review'),
        ('verified', 'Verified'),
    ]

    DOC_TYPE_CHOICES = [
        ('prescription', 'Prescription'),
        ('lab_report', 'Lab Report'),
        ('discharge', 'Discharge Summary'),
        ('id_card', 'Government ID'),
        ('other', 'Other Medical Slip'),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    session = models.ForeignKey(PatientSession, on_delete=models.CASCADE, related_name='medical_documents')
    document_type = models.CharField(max_length=30, choices=DOC_TYPE_CHOICES, default='prescription')
    image_file = models.ImageField(upload_to='medical_docs/%Y/%m/%d/')
    processed_image_file = models.ImageField(upload_to='medical_docs_processed/%Y/%m/%d/', null=True, blank=True)
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='uploaded')
    overall_confidence = models.FloatField(default=0.0)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"{self.get_document_type_display()} ({self.id}) - {self.status}"


class DocumentField(models.Model):
    """
    Individual extracted key-value from a medical document with confidence and review flag.
    """
    from .provenance import PROVENANCE_CHOICES

    document = models.ForeignKey(MedicalDocument, on_delete=models.CASCADE, related_name='fields')
    field_name = models.CharField(max_length=100)
    field_value = models.TextField()
    confidence = models.FloatField(default=0.0)
    needs_review = models.BooleanField(default=False)
    provenance = models.CharField(max_length=30, choices=PROVENANCE_CHOICES, default='ai_extracted')
    verified_by = models.ForeignKey('doctor.DoctorProfile', on_delete=models.SET_NULL, null=True, blank=True, related_name='verified_fields')
    verified_at = models.DateTimeField(null=True, blank=True)
    rejection_reason = models.TextField(blank=True, default='')

    def __str__(self):
        return f"{self.field_name}: {self.field_value[:30]} (conf={self.confidence:.2f})"


class DocumentMedication(models.Model):
    """
    Medication parsed from a prescription slip.
    """
    document = models.ForeignKey(MedicalDocument, on_delete=models.CASCADE, related_name='medications')
    name = models.CharField(max_length=255)
    dose = models.CharField(max_length=100, blank=True, default='')
    frequency = models.CharField(max_length=100, blank=True, default='')
    duration = models.CharField(max_length=100, blank=True, default='')
    confidence = models.FloatField(default=0.0)
    needs_review = models.BooleanField(default=False)

    def __str__(self):
        return f"{self.name} {self.dose} (conf={self.confidence:.2f})"


class DocumentLabResult(models.Model):
    """
    Laboratory observation parsed from a medical lab report.
    """
    document = models.ForeignKey(MedicalDocument, on_delete=models.CASCADE, related_name='lab_results')
    test_name = models.CharField(max_length=255)
    value = models.CharField(max_length=100)
    unit = models.CharField(max_length=50, blank=True, default='')
    reference_range = models.CharField(max_length=100, blank=True, default='')
    confidence = models.FloatField(default=0.0)
    loinc_code = models.CharField(max_length=50, blank=True, null=True)
    needs_review = models.BooleanField(default=False)

    def __str__(self):
        return f"{self.test_name}: {self.value} {self.unit}"


class AuditLog(models.Model):
    """
    Comprehensive audit log for privacy tracking and pipeline steps.
    """
    session = models.ForeignKey(PatientSession, on_delete=models.SET_NULL, null=True, blank=True, related_name='audit_logs')
    document = models.ForeignKey(MedicalDocument, on_delete=models.SET_NULL, null=True, blank=True, related_name='audit_logs')
    action = models.CharField(max_length=100, help_text="e.g. document_preprocess, ocr_paddle, handwriting_qwen, outbound_llm")
    step = models.CharField(max_length=100, blank=True, default='')
    model_used = models.CharField(max_length=100, blank=True, default='')
    latency_ms = models.FloatField(default=0.0)
    confidence = models.FloatField(null=True, blank=True)
    details = models.JSONField(default=dict, blank=True)
    timestamp = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-timestamp']

    def __str__(self):
        return f"AuditLog [{self.action}] - {self.timestamp}"