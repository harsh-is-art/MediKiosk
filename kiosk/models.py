# Django & Python Imports

import uuid
from django.db import models


# Daily Token Counter Model Definition

class DailyTokenCounter(models.Model):
    """
    Tracks daily token counts with atomic transactional locking.
    """

    # Database Fields

    date = models.DateField(primary_key=True)
    last_token = models.IntegerField(default=0)

    # String Representation

    def __str__(self):
        return f"{self.date}: {self.last_token}"


# Patient Session Model Definition

class PatientSession(models.Model):
    """
    Tracks a single patient kiosk session from start to finish.
    """

    # Session Status Choices

    STATUS_CHOICES = [
        ('active', 'Active'),
        ('completed', 'Completed'),
        ('abandoned', 'Abandoned'),
    ]

    # Supported Language Choices

    LANGUAGE_CHOICES = [
        ('en', 'English'),
        ('hi', 'Hindi'),
        ('ta', 'Tamil'),
        ('bn', 'Bengali'),
        ('mr', 'Marathi'),
    ]

    # Database Fields

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='active')
    language = models.CharField(max_length=5, choices=LANGUAGE_CHOICES, default='en')
    consent_given = models.BooleanField(default=False)
    abha_id = models.CharField(max_length=50, blank=True, default='')
    chief_complaints = models.JSONField(default=list, blank=True)
    selected_body_regions = models.JSONField(default=list, blank=True)
    token_number = models.IntegerField(null=True, blank=True)
    red_flags = models.JSONField(default=list, blank=True)
    clinician_reviewed = models.BooleanField(default=False, help_text='Whether session was reviewed by doctor')
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    # Model Meta Confi.

    class Meta:
        ordering = ['-created_at']

    # String Representation

    def __str__(self):
        return f"Session {self.id} ({self.get_status_display()})"


# Conversation Log Model Definition

class ConversationLog(models.Model):
    """
    Stores the full chat history for a session.
    """

    # Conversation Role Choices

    ROLE_CHOICES = [
        ('system', 'System'),
        ('assistant', 'Assistant'),
        ('user', 'User'),
    ]

    # Input Type Choices

    INPUT_TYPE_CHOICES = [
        ('text', 'Text'),
        ('voice', 'Voice'),
        ('button', 'Button'),
        ('body_map', 'Body Map'),
    ]

    # Database Fields

    session = models.ForeignKey(PatientSession, on_delete=models.CASCADE, related_name='conversations')
    role = models.CharField(max_length=10, choices=ROLE_CHOICES)
    content = models.TextField()
    input_type = models.CharField(max_length=10, choices=INPUT_TYPE_CHOICES, default='text')
    confidence = models.FloatField(null=True, blank=True)  # ASR confidence
    created_at = models.DateTimeField(auto_now_add=True)

    # Model Meta Confi.

    class Meta:
        ordering = ['created_at']

    # String Representation

    def __str__(self):
        return f"{self.role}: {self.content[:50]}"


# Document Upload Model Definition (Legacy compatibility)

